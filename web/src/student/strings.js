/* lib/i18n.js 的 LANG_LABEL 没有 my/fr（api.md 的 LANGS 有），这里补上。 */
export const LANG_LABEL_EXTRA = { my: 'မြန်မာ', fr: 'Français' }

/* 取一条界面文案：先问冻结的 i18n，再问本表，最后退回英文。
   vars 支持 {d} / {c} 这类占位符。 */
export function makeTr(lang) {
  const code = EXTRAS[lang] ? lang : 'en'
  const pack = EXTRAS[code]
  const fallback = EXTRAS.en
  return function tr(key, vars) {
    const fromI18n = t(lang, key)
    let text = fromI18n && fromI18n !== key ? fromI18n : pack[key] ?? fallback[key] ?? key
    if (vars) {
      for (const k of Object.keys(vars)) {
        text = text.split('{' + k + '}').join(String(vars[k]))
      }
    }
    return text
  }
}

/* 说给朗读引擎听的完整文本：一句话结论 + 全部行动项。
   句尾标点先去掉再拼，避免出现「..」这种双句号。 */
export function speechText(notice) {
  if (!notice) return ''
  const trimTail = (s) => String(s || '').trim().replace(/[.。!！?？;；]+$/, '')
  const one = trimTail(notice.one_line || notice.title)
  const actions = Array.isArray(notice.actions) ? notice.actions : []
  const lines = actions
    .slice()
    .sort((a, b) => (Number(a?.order) || 0) - (Number(b?.order) || 0))
    .map((a, i) => {
      const text = trimTail(a?.text)
      return text ? `${Number(a?.order) || i + 1}. ${text}` : ''
    })
    .filter(Boolean)
  return [one, ...lines].filter(Boolean).join('. ')
}
